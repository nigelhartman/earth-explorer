data class CapitalCity(
    val id: String,
    val name: String,
    val country: String,
    val latitude: Double,
    val longitude: Double,
) {
    fun distanceDegrees(latitude: Double, longitude: Double): Double {
        val lat1 = Math.toRadians(this.latitude)
        val lat2 = Math.toRadians(latitude)
        val dLat = lat2 - lat1
        val dLon = Math.toRadians(longitude - this.longitude)
        val a = sin(dLat / 2).pow(2) + cos(lat1) * cos(lat2) * sin(dLon / 2).pow(2)
        return Math.toDegrees(2 * asin(sqrt(a.coerceIn(0.0, 1.0))))
    }
}

