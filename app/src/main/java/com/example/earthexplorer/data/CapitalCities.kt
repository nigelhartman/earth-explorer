        name?.takeIf { it.startsWith("capital:") }?.removePrefix("capital:")
            ?.let { id -> all.firstOrNull { it.id == id } }

    fun nearby(latitude: Double, longitude: Double, radius: Double = 2.5): List<CapitalCity> =
        all.filter { it.distanceDegrees(latitude, longitude) <= radius }
            .sortedBy { it.distanceDegrees(latitude, longitude) }

    fun search(query: String, latitude: Double, longitude: Double): List<CapitalCity> =
        all.filter { query.isBlank() || it.name.contains(query.trim(), ignoreCase = true) ||
